const pad = (n: number) => String(n).padStart(2, "0");

export const GENRES: GenreGroup[] = RAW_GENRES.map(([name, subs], gi) => ({
  id: `g${pad(gi + 1)}`,
  name,
  subgenres: subs.map((s, si) => ({ id: `g${pad(gi + 1)}-s${pad(si + 1)}`, name: s })),
}));

export const ALL_SUBGENRE_IDS: string[] = GENRES.flatMap((g) => g.subgenres.map((s) => s.id));
export const ALL_DIRECTION_IDS: string[] = GENRES.flatMap((g) => [g.id, ...g.subgenres.map((s) => s.id)]);

export const genreNameById: Record<string, string> = Object.fromEntries(
  GENRES.flatMap((g) => [[g.id, g.name] as const, ...g.subgenres.map((s) => [s.id, s.name] as const)]),
);

